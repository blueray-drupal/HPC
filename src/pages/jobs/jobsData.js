export function getJobById(id) {
  const numericId = Number(id);
  const job = JOBS_ITEMS.find((item) => item.id === numericId);
  const detail = JOBS_DETAILS[numericId];

  if (!job || !detail) return null;

  return { ...job, ...detail };
}

export function filterJobs(items, { title = '' } = {}) {
  const normalizedTitle = title.trim().toLowerCase();

  if (!normalizedTitle) return items;

  return items.filter(
    (item) =>
      item.title.toLowerCase().includes(normalizedTitle) ||
      item.description.toLowerCase().includes(normalizedTitle) ||
      item.field.toLowerCase().includes(normalizedTitle),
  );
}
