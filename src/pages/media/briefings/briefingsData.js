export function getBriefingById(id) {
  if (!id) return null;
  return (
    MEDIA_BRIEFINGS_FALLBACK.find((item) => item.id === id || String(item.id) === String(id)) ?? null
  );
}

export function getBriefingBody(briefing) {
  if (!briefing) return [];
  return briefing.body?.length ? briefing.body : [briefing.description];
}
