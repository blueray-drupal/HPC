export function getNewsById(id) {
  if (!id) return null;
  return (
    NEWS_ITEMS_FALLBACK.find((item) => item.id === id || String(item.id) === String(id)) ?? null
  );
}

export function getNewsBody(item) {
  if (item.body?.length) return item.body;
  return [item.excerpt];
}

export function filterNews(items, { category, year, query }) {
  return items.filter((item) => {
    const matchesCategory =
      !category || item.categoryId === category || item.category === category;
    const matchesYear = !year || String(item.year) === year;
    const matchesQuery =
      !query ||
      item.title.toLowerCase().includes(query.trim().toLowerCase()) ||
      item.excerpt.toLowerCase().includes(query.trim().toLowerCase());
    return matchesCategory && matchesYear && matchesQuery;
  });
}

export function paginateNews(items, page, perPage) {
  const totalPages = Math.max(1, Math.ceil(items.length / perPage));
  const safePage = Math.min(Math.max(page, 1), totalPages);
  const start = (safePage - 1) * perPage;

  return {
    items: items.slice(start, start + perPage),
    currentPage: safePage,
    totalPages,
    totalItems: items.length,
  };
}
